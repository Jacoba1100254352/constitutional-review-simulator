        ["Claim", "Component", "Difference range", "Pattern", "CI +/$-$"], claim_rows,
        r"All 22 components are shown. $\dagger$ Additional diagnostics, not replacement endpoints. "
        "Stable requires every signed base estimate beyond the expected strict 0.01 threshold; sign-reversing requires both practical signs. "
        "Unsigned rows are descriptive-only. CI counts are unadjusted intervals above/below zero, out of 52. "
