def digest(path):
    with path.open("rb") as handle:
        return hashlib.file_digest(handle, "sha256").hexdigest()


def read_rows(path):
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def escape(value):
    replacements = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
                    "{": r"\{", "}": r"\}", "\\": r"\textbackslash{}"}
    return "".join(replacements.get(char, char) for char in str(value))


def number(value, places=4):
    rounded = round(float(value), places)
    return f"{0.0 if rounded == 0 else rounded:.{places}f}"


def span(row):
    return number(row["pointMin"]) + " to " + number(row["pointMax"])


def table(caption, label, columns, headings, rows, note, *, long=False):
    lines = ["% Auto-generated by paper/scripts/generate_historical_tables.py", r"{\small",
             r"\setlength{\tabcolsep}{3pt}"]
    heading = " & ".join(headings) + r" \\"
    if long:
        lines += [rf"\begin{{longtable}}{{{columns}}}", rf"\caption{{{caption}}}\label{{{label}}}\\",
                  r"\toprule", heading, r"\midrule", r"\endfirsthead", r"\toprule", heading,
                  r"\midrule", r"\endhead"]
    else:
        lines += [r"\begin{table}[hbt!]", r"\centering", rf"\caption{{{caption}}}\label{{{label}}}",
                  rf"\begin{{tabular}}{{{columns}}}", r"\toprule", heading, r"\midrule"]
    lines += [" & ".join(row) + r" \\" for row in rows]
    lines += [r"\bottomrule", r"\end{longtable}" if long else r"\end{tabular}",
              r"\par\noindent\begin{minipage}{0.98\linewidth}\footnotesize " + note + r"\end{minipage}"]
    if not long:
        lines.append(r"\end{table}")
    return "\n".join(lines + ["}", ""]).encode()


def load_evidence(root):
    reports = root / "reports"
    analysis_path = reports / f"{STUDY}-analysis-manifest.json"
    validation_path = reports / f"{STUDY}-analysis-validation.json"
    analysis = json.loads(analysis_path.read_text())
    validation = json.loads(validation_path.read_text())
    lock_path = root / "config/historical-benchmark/first-evaluation-lock.json"
    lock = json.loads(lock_path.read_text())
    inputs = {**analysis["inputSha256"], **lock["sha256"]}
    inputs.update({f"reports/{STUDY}{suffix}": value for suffix, value in analysis["outputSha256"].items()})
    inputs.update({str(path.relative_to(root)): digest(path) for path in (analysis_path, validation_path, lock_path)})
    inputs["scripts/check_historical_analysis.py"] = validation["inputSha256"]["validator"]
    if validation["inputSha256"]["analysisManifest"] != digest(analysis_path):
        raise ValueError("publication analysis validation is stale")
    for relative, expected in inputs.items():
        if digest(root / relative) != expected:
            raise ValueError("publication evidence hash mismatch: " + relative)
    first = json.loads((reports / f"{EMPIRICAL}-first-evaluation.json").read_text())
    forecasts_path = root / "config/historical-benchmark/forecasts-2025.json"
    protocol_path = root / "config/historical-benchmark/protocol-v1.json"
    for path, key in ((forecasts_path, "forecastSha256"), (protocol_path, "protocolSha256")):
        if digest(path) != first["provenance"][key]:
            raise ValueError("publication frozen input mismatch")
        inputs[str(path.relative_to(root))] = digest(path)
    tables = {suffix: read_rows(reports / f"{STUDY}{suffix}") for suffix in analysis["rows"]}
    return first, json.loads(forecasts_path.read_text()), json.loads(protocol_path.read_text()), tables, inputs


