#!/usr/bin/env python3
"""Generate compact LaTeX tables for the supplementary appendix."""

from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
REPORT_DIR = ROOT / "reports"
TABLE_DIR = ROOT / "paper" / "tables"


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def latex_escape(value: str) -> str:
    replacements = {
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    return "".join(replacements.get(char, char) for char in value)


def num(value: str | float) -> str:
    return f"{float(value):.3f}"


def write(name: str, content: str) -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    (TABLE_DIR / name).write_text(content, encoding="utf-8")


def scenario_matrix() -> None:
    rows = read_rows(REPORT_DIR / "constitutional-review-campaign-v0.csv")
    lines = [
        "% Auto-generated by paper/scripts/generate_supplement.py",
        r"\begin{longtable}{@{}p{0.18\linewidth}p{0.24\linewidth}rrrrr@{}}",
        r"\caption{Full starter-campaign scenario matrix.}\label{tab:supp-scenario-matrix}\\",
        r"\toprule",
        r"Case & Scenario & Score & Rights & Shadow $\downarrow$ & Legitimacy & Cost $\downarrow$ \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Case & Scenario & Score & Rights & Shadow $\downarrow$ & Legitimacy & Cost $\downarrow$ \\",
        r"\midrule",
        r"\endhead",
    ]
    for row in rows:
        lines.append(
            " & ".join(
                [
                    latex_escape(row["caseName"]),
                    latex_escape(row["scenario"]),
                    num(row["directionalScore"]),
                    num(row["rightsProtection"]),
                    num(row["shadowDocketAbuse"]),
                    num(row["legitimacy"]),
                    num(row["totalInstitutionalCost"]),
                ]
            )
            + r" \\"
        )
    lines.extend([r"\bottomrule", r"\end{longtable}", ""])
    write("supplement_scenario_matrix.tex", "\n".join(lines))


def sensitivity_matrix() -> None:
    rows = read_rows(REPORT_DIR / "constitutional-review-sensitivity-v1.csv")
    lines = [
        "% Auto-generated by paper/scripts/generate_supplement.py",
        r"\begin{longtable}{@{}p{0.22\linewidth}p{0.24\linewidth}rrrr@{}}",
        r"\caption{Sensitivity-campaign diagnostic matrix.}\label{tab:supp-sensitivity}\\",
        r"\toprule",
        r"Stress case & Scenario & Score & Stability & Conflict $\downarrow$ & Trust \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Stress case & Scenario & Score & Stability & Conflict $\downarrow$ & Trust \\",
        r"\midrule",
        r"\endhead",
    ]
    for row in rows:
        lines.append(
            " & ".join(
                [
                    latex_escape(row["caseName"]),
                    latex_escape(row["scenario"]),
                    num(row["directionalScore"]),
                    num(row["legalStability"]),
                    num(row["constitutionalConflict"]),
                    num(row["publicTrust"]),
                ]
            )
            + r" \\"
        )
    lines.extend([r"\bottomrule", r"\end{longtable}", ""])
    write("supplement_sensitivity_matrix.tex", "\n".join(lines))


def artifact_inventory() -> None:
    paths = sorted(REPORT_DIR.glob("constitutional-review-*.csv")) + sorted(REPORT_DIR.glob("constitutional-review-*.csv.gz"))
    lines = [
        "% Auto-generated by paper/scripts/generate_supplement.py",
        r"\begin{longtable}{@{}p{0.66\linewidth}r@{}}",
        r"\caption{Generated report artifact inventory.}\label{tab:supp-artifacts}\\",
        r"\toprule",
        r"Artifact & Size (KB) \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Artifact & Size (KB) \\",
        r"\midrule",
        r"\endhead",
    ]
    for path in paths:
        size_kb = path.stat().st_size / 1024
        lines.append(f"{latex_escape(str(path.relative_to(ROOT)))} & {size_kb:.1f} \\\\")
    lines.extend([r"\bottomrule", r"\end{longtable}", ""])
    write("supplement_artifacts.tex", "\n".join(lines))


def main() -> None:
    scenario_matrix()
    sensitivity_matrix()
    artifact_inventory()


if __name__ == "__main__":
    main()
