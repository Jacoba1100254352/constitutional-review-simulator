def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def latex_escape(value: str) -> str:
    replacements = {
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    return "".join(replacements.get(char, char) for char in value)


def latex_code_list(value: str) -> str:
    escaped = latex_escape(value).replace("; ", r";\newline ")
    breaks = {
        "ConstitutionalReviewProcess": r"Constitutional\hspace{0pt}Review\hspace{0pt}Process",
        "DecisionMechanismModel": r"Decision\hspace{0pt}Mechanism\hspace{0pt}Model",
        "PostDecisionResponseModel": r"Post\hspace{0pt}Decision\hspace{0pt}Response\hspace{0pt}Model",
        "EmergencyDocketModel": r"Emergency\hspace{0pt}Docket\hspace{0pt}Model",
        "InstitutionalCostModel": r"Institutional\hspace{0pt}Cost\hspace{0pt}Model",
        "CampaignCalibrationEvaluator": r"Campaign\hspace{0pt}Calibration\hspace{0pt}Evaluator",
        "DirectionalScoreModel": r"Directional\hspace{0pt}Score\hspace{0pt}Model",
        "OutcomeScoreModel": r"Outcome\hspace{0pt}Score\hspace{0pt}Model",
    }
    for raw, replacement in breaks.items():
        escaped = escaped.replace(raw, replacement)
    return escaped


def num(value: str | float) -> str:
    return f"{float(value):.3f}"


