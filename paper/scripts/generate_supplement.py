def mechanism_label(value: str) -> str:
    return MECHANISM_LABELS.get(value, value.replace("_", " "))


def write(name: str, content: str) -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    (TABLE_DIR / name).write_text(content, encoding="utf-8")


def scenario_matrix() -> None:
    rows = read_rows(REPORT_DIR / "constitutional-review-campaign-v0.csv")
    lines = [
        "% Auto-generated by paper/scripts/generate_supplement.py",
        r"{\scriptsize",
        r"\setlength{\tabcolsep}{2pt}",
        r"\begin{longtable}{@{}L{0.12\linewidth}L{0.23\linewidth}L{0.11\linewidth}rrrrrr@{}}",
        r"\caption{Full main-campaign scenario matrix.}\label{tab:supp-scenario-matrix}\\",
        r"\toprule",
        r"Case & Scenario & Mechanism & Score & Dem. const. & Rights & Veto $\downarrow$ & Culture $\downarrow$ & Cost $\downarrow$ \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Case & Scenario & Mechanism & Score & Dem. const. & Rights & Veto $\downarrow$ & Culture $\downarrow$ & Cost $\downarrow$ \\",
        r"\midrule",
        r"\endhead",
    ]
    for row in rows:
        lines.append(
            " & ".join(
                [
                    latex_escape(row["caseName"]),
                    latex_escape(row["scenario"]),
                    latex_escape(mechanism_label(row["reviewMechanism"])),
                    num(row["directionalScore"]),
                    num(row["democraticConstitutionalism"]),
                    num(row["rightsProtection"]),
                    num(row["vetoRelocationRisk"]),
                    num(row["politicalCultureSensitivity"]),
                    num(row["totalInstitutionalCost"]),
                ]
            )
            + r" \\"
        )
    lines.extend([r"\bottomrule", r"\end{longtable}", r"}", ""])
    write("supplement_scenario_matrix.tex", "\n".join(lines))


