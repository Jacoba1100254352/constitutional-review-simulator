def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def baseline_rows() -> list[dict[str, str]]:
    return [row for row in read_rows(BASELINE_CSV) if row["caseKey"] == "baseline"]


def row_float(row: dict[str, str], field: str) -> float:
    return float(row[field])


def coord(value: float, lower: float, upper: float, start: float, length: float) -> float:
    if upper == lower:
        return start + (length / 2.0)
    return start + ((value - lower) / (upper - lower)) * length


def write(name: str, content: str) -> None:
    FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    (FIGURE_DIR / name).write_text(content, encoding="utf-8")


def fmt(value: float) -> str:
    return f"{value:.1f}"


def sign(value: float) -> int:
    if value > 0:
        return 1
    if value < 0:
        return -1
    return 0


def figure_label(key: str) -> str:
    label = SCENARIO_LABELS[key]
    return f"{label}*" if key == "current-federal-court" else label


def leader_line(
        start_x: float,
        start_y: float,
        end_x: float,
        end_y: float,
        color: str = "black!55",
        samples: int = 10,
) -> str:
    mid_x = (start_x + end_x) / 2.0
    mid_y = (start_y + end_y) / 2.0
    return (
        rf"{{\color{{{color}}}\qbezier[{samples}]"
        rf"({fmt(start_x)},{fmt(start_y)})"
        rf"({fmt(mid_x)},{fmt(mid_y)})"
        rf"({fmt(end_x)},{fmt(end_y)})}}"
    )


