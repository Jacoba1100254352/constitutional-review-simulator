    left, bottom, width, height = 22.0, 15.0, 92.0, 58.0
    x_min, x_max = 0.25, 0.65
    y_min, y_max = 0.60, 0.78
    offsets = {
        "CUR": (-3.4, 5.2, "r"),
        "EMR": (7.5, 12.0, "l"),
        "DUAL": (3.2, 2.0, "l"),
        "COUNC": (-0.5, 6.0, "c"),
        "OVR": (5.4, -6.6, "l"),
        "HYB": (4.0, 4.0, "l"),
        "WFR": (-4.4, 4.2, "r"),
        "SUS": (7.4, -8.8, "l"),
        "PRE": (-7.0, 2.0, "r"),
        "ABS": (4.0, 2.6, "l"),
        "OMB": (4.0, -5.0, "l"),
        "DEF": (-4.0, -5.0, "r"),
        "RIS": (-4.0, 2.8, "r"),
        "MLR": (8.0, 7.5, "l"),
    }
    lines = [
        "% Auto-generated by paper/scripts/generate_figures.py",
        r"\begingroup",
        r"\setlength{\unitlength}{1mm}",
        r"\begin{picture}(128,86)",
        r"\scriptsize",
    ]
    for tick in [0.30, 0.40, 0.50, 0.60]:
        x = coord(tick, x_min, x_max, left, width)
        lines.append(rf"\put({fmt(x)},{fmt(bottom)}){{\color{{black!15}}\line(0,1){{{fmt(height)}}}}}")
        lines.append(rf"\put({fmt(x)},{fmt(bottom - 4)}){{\makebox(0,0){{{tick:.2f}}}}}")
    for tick in [0.60, 0.65, 0.70, 0.75]:
        y = coord(tick, y_min, y_max, bottom, height)
        lines.append(rf"\put({fmt(left)},{fmt(y)}){{\color{{black!15}}\line(1,0){{{fmt(width)}}}}}")
        lines.append(rf"\put({fmt(left - 4)},{fmt(y)}){{\makebox(0,0)[r]{{{tick:.2f}}}}}")
    lines.append(rf"\put({fmt(left)},{fmt(bottom)}){{\line(1,0){{{fmt(width)}}}}}")
    lines.append(rf"\put({fmt(left)},{fmt(bottom)}){{\line(0,1){{{fmt(height)}}}}}")
    lines.append(r"\put(26,79){\makebox(0,0)[l]{\rule{1.8mm}{1.8mm} court architecture \quad \raisebox{-0.3mm}{\framebox(1.8,1.8){}} mechanism scenario}}")
    for row in rows:
        key = row["scenarioKey"]
        label = SCENARIO_LABELS[key]
        x = coord(row_float(row, "totalInstitutionalCost"), x_min, x_max, left, width)
        y = coord(row_float(row, "democraticConstitutionalism"), y_min, y_max, bottom, height)
        color = "black"
        size = 2.1 if key == "current-federal-court" else 1.7
        if row.get("scenarioKind") == "synthetic_mechanism":
            lines.append(rf"\put({fmt(x - size / 2.0)},{fmt(y - size / 2.0)}){{\color{{{color}}}\framebox({fmt(size)},{fmt(size)}){{}}}}")
        else:
            lines.append(rf"\put({fmt(x)},{fmt(y)}){{\makebox(0,0){{\color{{{color}}}\rule{{{size}mm}}{{{size}mm}}}}}}")
        dx, dy, align = offsets[label]
        line_start_x = x + (sign(dx) * (size / 2.0 + 0.4))
        line_start_y = y + (sign(dy) * (size / 2.0 + 0.4))
        label_x = x + dx
        label_y = y + dy
        if abs(dx) >= 3.5 or abs(dy) >= 3.5:
            label_edge_x = label_x
            if align == "l":
                label_edge_x -= 0.9
            elif align == "r":
                label_edge_x += 0.9
            lines.append(leader_line(line_start_x, line_start_y, label_edge_x, label_y, "black!45", 8))
        lines.append(rf"\put({fmt(x + dx)},{fmt(y + dy)}){{\makebox(0,0)[{align}]{{{figure_label(key)}}}}}")
    lines.append(r"\put(68,4){\makebox(0,0){total institutional cost}}")
    lines.append(r"\put(4,45){\rotatebox{90}{\makebox(0,0){democratic constitutionalism}}}")
    lines.extend([r"\end{picture}", r"\endgroup", ""])
    write("cost_score_scatter.tex", "\n".join(lines))


